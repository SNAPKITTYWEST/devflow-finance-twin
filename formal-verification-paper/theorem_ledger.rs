#![allow(dead_code, unused_variables, unused_imports)]
use std::collections::{BTreeMap, BTreeSet};
use std::time::{SystemTime, UNIX_EPOCH};

#[derive(Clone, Debug, PartialEq, Eq)]
enum Status { Pending, Proved, Refuted, UnderSpecified, Unproven, Rejected }

#[derive(Clone, Debug)]
struct Claim { id: String, proposition: String, negation: String, status: Status, evidence: Vec<String>, deps: BTreeSet<String> }

#[derive(Default)]
struct Ledger { claims: BTreeMap<String, Claim>, defects: Vec<String>, pass: usize }

fn now() -> u64 { SystemTime::now().duration_since(UNIX_EPOCH).unwrap().as_secs() }

fn add_claim(ledger: &mut Ledger, id: &str, proposition: &str, negation: &str) {
    ledger.claims.insert(id.to_string(), Claim { id:id.into(), proposition:proposition.into(), negation:negation.into(), status:Status::Pending, evidence:Vec::new(), deps:BTreeSet::new() });
}

fn record(ledger: &mut Ledger, id: &str, status: Status, evidence: &str) {
    if let Some(c)=ledger.claims.get_mut(id) { c.status=status; c.evidence.push(evidence.into()); }
}

fn audit(ledger: &mut Ledger) {
    ledger.pass += 1;
    let ids: Vec<String>=ledger.claims.keys().cloned().collect();
    for id in ids {
        let c=ledger.claims.get(&id).cloned().unwrap();
        if c.evidence.is_empty() { ledger.defects.push(format!("{} has no evidence",id)); }
        if matches!(c.status, Status::Proved) && c.evidence.iter().any(|e| e.contains("axiom-only")) {
            ledger.defects.push(format!("{} labeled proved from axiom-only",id));
            record(&mut ledger,&id,Status::Rejected,"proof label invalidated by audit");
        }
    }
}

