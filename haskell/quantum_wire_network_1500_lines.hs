qwire :: Bool -> Qubit -> Circ Qubit
qwire b q = do
  if b then gate_X q else return q

wireBank :: [Bool] -> Circ [Qubit]
wireBank bs = do
  qs <- mapM qinit bs
  mapM (uncurry qwire) (zip bs qs)

